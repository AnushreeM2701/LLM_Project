"""
Error-type classification (RQ1) and error-step location (RQ2).

The judge prompt design (evaluate the model's reasoning on its own
mathematical merits, never compare against a reference solution) is ported
from the prior pipeline's app/evaluation/error_evaluation.py unchanged —
that framing was reviewed and found sound, and is also why AIME's missing
step-by-step reference solutions are a non-issue (see docs/methodology.md).

What's new: the primary judge (Gemini) is one of the three models under
evaluation, which the review flagged as a conflict of interest in the
central model comparison. Rather than fully replacing it (cost), a fixed
sample is independently re-judged by a neutral model not under evaluation
(llama-3.3-70b-versatile via Groq — see src/models/neutral_judge.py), and inter-judge
agreement (Cohen's kappa) is computed and reported. If agreement is high,
the judge choice demonstrably isn't biasing the results; if it's low, that
itself is an important, honestly-reported finding.
"""

import json
import os
import time

import pandas as pd

from config.config import (
    ERROR_TYPES,
    PRIMARY_JUDGE_MODEL,
    NEUTRAL_JUDGE_MODEL_ID,
    VALIDATION_SAMPLE_SIZE,
    DATASET_SEED,
    STATS_DIR,
)
from src.models.model_loader import get_model
from src.models.neutral_judge import generate_response as neutral_judge_generate
from src.utils.io import load_results, save_results

_MAX_RETRIES = 5
_WAIT_SECONDS = 30


# ==========================================================
# JUDGE PROMPT
# ==========================================================

def build_error_prompt(question, category, ground_truth, model_answer, reasoning) -> str:

    return f"""
You are an independent mathematics examiner evaluating anonymous mathematical solutions.

The reasoning below was generated by an AI system.
You DO NOT know which AI model produced it.
Evaluate it solely on its mathematical correctness.

Your task is to identify the FIRST mathematical reasoning error, if one exists.

Do NOT compare the reasoning with a preferred solving method.

Evaluate only the reasoning provided.

==================================================
QUESTION
==================================================

{question}

==================================================
CATEGORY
==================================================

{category}

Category Guidance

Probability:
Check independence, conditional probability,
counting, probability rules and normalization.

Combinatorics:
Check counting principles, permutations,
combinations and over-counting.

Algebra:
Check algebraic manipulation,
simplification and equation solving.

Number Theory:
Check divisibility,
modular arithmetic,
integer properties and parity.

==================================================
REFERENCE FINAL ANSWER
==================================================

{ground_truth}

Use this ONLY to verify whether the final answer is correct.
Do NOT compare the reasoning with any reference solution.

==================================================
MODEL REASONING
==================================================

{reasoning}

==================================================
MODEL FINAL ANSWER
==================================================

{model_answer}

==================================================
TASK
==================================================

Read the reasoning carefully.

Count ONLY major mathematical reasoning steps.

Ignore formatting,
headings,
bullet points,
or repeated explanations.

Identify the FIRST step where the mathematical reasoning becomes incorrect.

If the reasoning is mathematically correct
but the final answer could not be extracted,
return

"Answer Extraction Error"

If the reasoning and final answer are both correct,
return

"Correct"

Choose EXACTLY ONE error type from:

{ERROR_TYPES}

This category is used for statistical comparison across models, so it MUST
be exactly one of the options above, even if the fit feels approximate.

Separately, describe the SPECIFIC error pattern in your own words -- a
short phrase naming the exact mistake (e.g. "double-counted symmetric
cases", "used combination formula where permutation was needed", "ignored
the stated domain restriction x>0", "sign error expanding (a-b)^2"). This
is not a restatement of the category and not a justification for picking
it -- it is a specific, concrete description of what the model actually
did wrong, precise enough that someone could group similar subtypes
together later without re-reading every response.

==================================================
OUTPUT FORMAT
==================================================

Return ONLY valid JSON.

{{
    "error_step": integer,
    "error_type": "...",
    "error_subtype": "Short specific phrase, max 10 words.",
    "confidence": "High|Medium|Low",
    "justification": "One sentence. Maximum 25 words."
}}

Rules

- Return JSON only.
- No markdown.
- No code fences.
- No explanations.
- No extra text.
"""


def classify_error(question, category, ground_truth, model_answer, reasoning, judge_generate_fn) -> dict:

    prompt = build_error_prompt(question, category, ground_truth, model_answer, reasoning)

    for attempt in range(_MAX_RETRIES):

        try:
            result = judge_generate_fn(prompt)
            text = result.text.strip().replace("```json", "").replace("```", "").strip()

            start = text.find("{")
            end = text.rfind("}")
            text = text[start:end + 1]

            parsed = json.loads(text)

            # str()-coerce every field: the prompt asks for "error_step" as
            # a JSON integer, and the judge model follows that literally, so
            # parsed.get("error_step") is a Python int here -- assigning an
            # int into these all-text results columns raises a TypeError
            # under pandas' strict string dtype. All fields are stored as
            # free text regardless of what JSON type the judge happens to
            # return, so coercing here is always correct, not just a
            # workaround for this one field.
            return {
                "Error Step": str(parsed.get("error_step", "")),
                "Error Type": str(parsed.get("error_type", "Other")),
                "Error Subtype": str(parsed.get("error_subtype", "")),
                "Confidence": str(parsed.get("confidence", "Low")),
                "Justification": str(parsed.get("justification", "")),
            }

        except Exception:
            print(f"Judge retry {attempt + 1}/{_MAX_RETRIES}")
            time.sleep(_WAIT_SECONDS)

    return {
        "Error Step": "",
        "Error Type": "Other",
        "Error Subtype": "",
        "Confidence": "Low",
        "Justification": "Classification failed.",
    }


# ==========================================================
# PRIMARY JUDGE PASS (Gemini)
# ==========================================================

def run_primary_judge():

    results = load_results()
    judge_generate_fn = get_model(PRIMARY_JUDGE_MODEL)

    total_to_classify = (
        (results["Answer Correct"].astype(str).str.lower() == "false")
        & (results["Confidence"].astype(str).str.strip() == "")
    ).sum()

    completed = 0

    for index, row in results.iterrows():

        is_correct = str(row["Answer Correct"]).strip().lower() == "true"

        if is_correct:
            if str(row["Error Type"]).strip() == "":
                results.at[index, "Error Type"] = "Correct"
            continue

        if str(row["Confidence"]).strip() != "":
            continue  # already classified

        if str(row["Model Final Answer"]).strip() == "":
            results.at[index, "Error Type"] = "Answer Extraction Error"
            results.at[index, "Confidence"] = "High"
            results.at[index, "Justification"] = "Parser failed to extract the final answer."
            results.at[index, "Judge Model"] = PRIMARY_JUDGE_MODEL
            completed += 1
            continue

        print(f"\nJudging {row['Question ID']} | {row['Model']} | {row['Prompt']}")

        classification = classify_error(
            question=row["Question"],
            category=row["Category"],
            ground_truth=row["Ground Truth Answer"],
            model_answer=row["Model Final Answer"],
            reasoning=row["Model Response"],
            judge_generate_fn=judge_generate_fn,
        )

        for col in ["Error Step", "Error Type", "Error Subtype", "Confidence", "Justification"]:
            results.at[index, col] = classification[col]
        results.at[index, "Judge Model"] = PRIMARY_JUDGE_MODEL

        completed += 1
        print(f"Judged {completed}/{total_to_classify}")

        save_results(results)  # checkpoint every row, matches prior pipeline's pattern

    save_results(results)

    print("\nPrimary judging complete.")
    print(results["Error Type"].value_counts())

    return results


# ==========================================================
# NEUTRAL-JUDGE VALIDATION SAMPLE
# ==========================================================

def cohen_kappa(labels_a, labels_b) -> float:
    """Standard Cohen's kappa, computed from scratch to avoid adding a
    dependency for one metric. See src/utils/stats.py for the shared
    hypothesis-testing helpers used elsewhere in analysis."""

    n = len(labels_a)
    categories = sorted(set(labels_a) | set(labels_b))
    idx = {c: i for i, c in enumerate(categories)}
    k = len(categories)

    confusion = [[0] * k for _ in range(k)]
    for a, b in zip(labels_a, labels_b):
        confusion[idx[a]][idx[b]] += 1

    po = sum(confusion[i][i] for i in range(k)) / n

    row_sums = [sum(row) for row in confusion]
    col_sums = [sum(confusion[i][j] for i in range(k)) for j in range(k)]
    pe = sum(row_sums[i] * col_sums[i] for i in range(k)) / (n * n)

    if pe == 1:
        return 1.0

    return (po - pe) / (1 - pe)


def run_neutral_validation():
    """Re-judges a fixed sample of primary-judged rows with a neutral model
    (not under evaluation) and reports inter-judge agreement. Does NOT
    overwrite the primary judge's columns in the canonical results file —
    writes a separate validation table to outputs/stats/."""

    results = load_results()

    judged = results[
        (results["Answer Correct"].astype(str).str.lower() == "false")
        & (results["Error Type"].astype(str).str.strip() != "")
        & (results["Confidence"].astype(str).str.strip() != "")
    ].copy()

    sample_size = min(VALIDATION_SAMPLE_SIZE, len(judged))
    sample = judged.sample(n=sample_size, random_state=DATASET_SEED)

    print(f"Validating {sample_size} primary-judged rows against neutral judge "
          f"({NEUTRAL_JUDGE_MODEL_ID})...")

    validation_rows = []

    for i, (_, row) in enumerate(sample.iterrows(), 1):

        neutral_classification = classify_error(
            question=row["Question"],
            category=row["Category"],
            ground_truth=row["Ground Truth Answer"],
            model_answer=row["Model Final Answer"],
            reasoning=row["Model Response"],
            judge_generate_fn=neutral_judge_generate,
        )

        validation_rows.append({
            "Experiment ID": row["Experiment ID"],
            "Primary Judge Error Type": row["Error Type"],
            "Neutral Judge Error Type": neutral_classification["Error Type"],
            "Agree": row["Error Type"] == neutral_classification["Error Type"],
        })

        print(f"Validated {i}/{sample_size}")

    validation_df = pd.DataFrame(validation_rows)

    kappa = cohen_kappa(
        validation_df["Primary Judge Error Type"].tolist(),
        validation_df["Neutral Judge Error Type"].tolist(),
    )
    agreement_rate = validation_df["Agree"].mean()

    os.makedirs(STATS_DIR, exist_ok=True)
    validation_df.to_csv(os.path.join(STATS_DIR, "judge_agreement_detail.csv"), index=False)

    summary = pd.DataFrame([{
        "Sample Size": sample_size,
        "Raw Agreement Rate": agreement_rate,
        "Cohen Kappa": kappa,
        "Primary Judge": PRIMARY_JUDGE_MODEL,
        "Neutral Judge": NEUTRAL_JUDGE_MODEL_ID,
    }])
    summary.to_csv(os.path.join(STATS_DIR, "judge_agreement_summary.csv"), index=False)

    print(f"\nRaw agreement: {agreement_rate:.1%}  |  Cohen's kappa: {kappa:.3f}")
    print(f"Written -> {os.path.join(STATS_DIR, 'judge_agreement_summary.csv')}")

    return summary


if __name__ == "__main__":
    run_primary_judge()
    run_neutral_validation()
