import json
import os
import time

import pandas as pd

from app.models.model_loader import get_model
from app.utils.csv_to_excel import csv_to_excel

# ==========================================================
# FILE PATHS
# ==========================================================

RESULTS_PATH = "data/results/experiment_results.csv"

CHECKPOINT_INTERVAL = 1

MAX_RETRIES = 5

WAIT_TIME = 30


# ==========================================================
# ERROR TAXONOMY
# ==========================================================

ERROR_TYPES = [

    "Correct",

    "Arithmetic Error",

    "Algebraic Manipulation Error",

    "Probability Reasoning Error",

    "Combinatorial Counting Error",

    "Number Theory Error",

    "Formula Misapplication",

    "Incorrect Assumption",

    "Logical Reasoning Error",

    "Incomplete Reasoning",

    "Answer Extraction Error",

    "Other"

]


# ==========================================================
# LOAD RESULTS
# ==========================================================

print()

print("=" * 60)
print("Loading Experiment Results...")
print("=" * 60)

results = pd.read_csv(RESULTS_PATH)


# ==========================================================
# CREATE NEW COLUMNS
# ==========================================================

required_columns = [

    "Error Step",

    "Error Type",

    "Confidence",

    "Justification"

]

for column in required_columns:

    if column not in results.columns:

        results[column] = ""

# Force text columns
results["Error Type"] = results["Error Type"].fillna("").astype(str)
results["Confidence"] = results["Confidence"].fillna("").astype(str)
results["Justification"] = results["Justification"].fillna("").astype(str)

# Error Step can stay numeric/object
results["Error Step"] = results["Error Step"].astype(object)


# ==========================================================
# LOAD JUDGE MODEL
# ==========================================================

JUDGE_MODEL = "gemini"

judge = get_model(JUDGE_MODEL)
# ==========================================================
# BUILD PROMPT
# ==========================================================

def build_error_prompt(
    question,
    category,
    ground_truth,
    model_answer,
    reasoning
):

    prompt = f"""
You are an independent mathematics examiner evaluating anonymous mathematical solutions.

The reasoning below was generated by an AI system.
You DO NOT know which AI model produced it.
Evaluate it solely on its mathematical correctness.

Your task is to identify the FIRST mathematical reasoning error, if one exists.

Do NOT compare the reasoning with a preferred solving method.

Evaluate only the reasoning provided.

==================================================
QUESTION
==================================================

{question}

==================================================
CATEGORY
==================================================

{category}

Category Guidance

Probability:
Check independence, conditional probability,
counting, probability rules and normalization.

Combinatorics:
Check counting principles, permutations,
combinations and over-counting.

Algebra:
Check algebraic manipulation,
simplification and equation solving.

Number Theory:
Check divisibility,
modular arithmetic,
integer properties and parity.

==================================================
REFERENCE FINAL ANSWER
==================================================

{ground_truth}

Use this ONLY to verify whether the final answer is correct.
Do NOT compare the reasoning with any reference solution.

==================================================
MODEL REASONING
==================================================

{reasoning}

==================================================
MODEL FINAL ANSWER
==================================================

{model_answer}

==================================================
TASK
==================================================

Read the reasoning carefully.

Count ONLY major mathematical reasoning steps.

Ignore formatting,
headings,
bullet points,
or repeated explanations.

Identify the FIRST step where the mathematical reasoning becomes incorrect.

If the reasoning is mathematically correct
but the final answer could not be extracted,
return

"Answer Extraction Error"

If the reasoning and final answer are both correct,
return

"Correct"

Choose EXACTLY ONE error type from:

{ERROR_TYPES}

==================================================
OUTPUT FORMAT
==================================================

Return ONLY valid JSON.

{{
    "error_step": integer,
    "error_type": "...",
    "confidence": "High|Medium|Low",
    "justification": "One sentence. Maximum 25 words."
}}

Rules

- Return JSON only.
- No markdown.
- No code fences.
- No explanations.
- No extra text.
"""

    return prompt

# ==========================================================
# CLASSIFY ONE ERROR
# ==========================================================

def classify_error(
    question,
    category,
    ground_truth,
    model_answer,
    reasoning
):

    prompt = build_error_prompt(
        question,
        category,
        ground_truth,
        model_answer,
        reasoning
    )

    for attempt in range(MAX_RETRIES):

        try:

            response = judge(prompt).strip()

            response = (
                response
                .replace("```json", "")
                .replace("```", "")
                .strip()
            )

            start = response.find("{")
            end = response.rfind("}")

            response = response[start:end+1]

            result = json.loads(response)

            return {
                "Error Step": result.get("error_step", ""),
                "Error Type": result.get("error_type", "Other"),
                "Confidence": result.get("confidence", "Low"),
                "Justification": result.get("justification", "")
            }

        except Exception:

            print(f"Retry {attempt+1}/{MAX_RETRIES}")
            time.sleep(WAIT_TIME)

    return {
        "Error Step": "",
        "Error Type": "Other",
        "Confidence": "Low",
        "Justification": "Classification failed."
    }


# ==========================================================
# SAVE PROGRESS
# ==========================================================

def save_progress(df):

    df.to_csv(

        RESULTS_PATH,

        index=False

    )

    csv_to_excel(

        RESULTS_PATH

    )

    print()

    print("=" * 60)

    print("Progress Saved")

    print("=" * 60)

# ==========================================================
# RUN ERROR EVALUATION
# ==========================================================

def run_error_evaluation():

    print()
    print("=" * 60)
    print("Starting Error Evaluation")
    print("=" * 60)

    total_errors = len(
        results[
            results["Answer Correct"] == False
        ]
    )

    completed = 0

    for index, row in results.iterrows():

        # ---------------------------------------------
        # Skip Correct Answers
        # ---------------------------------------------

        if row["Answer Correct"] == True:

            if row["Error Type"] == "":

                results.at[
                    index,
                    "Error Type"
                ] = "Correct"

            continue

        # ---------------------------------------------
        # Skip Already Classified
        # ---------------------------------------------

        if pd.notna(row["Confidence"]):

            if str(row["Confidence"]).strip() != "":

                completed += 1

                continue

        print()

        print(
            f"Question {row['Question Number']} | "
            f"{row['Model']} | "
            f"{row['Prompt']}"
        )
        if str(row["Model Final Answer"]).strip() == "":

            results.at[index, "Error Type"] = "Answer Extraction Error"

            results.at[index, "Confidence"] = "High"

            results.at[index, "Justification"] = (
                "Parser failed to extract the final answer."
            )

            completed += 1

            continue
        classification = classify_error(

            question=row["Question"],

            category=row["Category"],

            ground_truth=row["Ground Truth Answer"],

            model_answer=row["Model Final Answer"],

            reasoning=row["Model Response"]

        )
        
        results.at[
            index,
            "Error Step"
        ] = classification["Error Step"]

        results.at[
            index,
            "Error Type"
        ] = classification["Error Type"]

        results.at[
            index,
            "Confidence"
        ] = classification["Confidence"]

        results.at[
            index,
            "Justification"
        ] = classification["Justification"]

        completed += 1

        print(
            f"Completed "
            f"{completed}/{total_errors}"
        )

        # ---------------------------------------------
        # Checkpoint Save
        # ---------------------------------------------

        if completed % CHECKPOINT_INTERVAL == 0:

            save_progress(results)

    # ---------------------------------------------
    # Final Save
    # ---------------------------------------------

    save_progress(results)

    print()

    print("=" * 60)
    print("Error Evaluation Completed")
    print("=" * 60)

    print()

    print(
        results[
            "Error Type"
        ].value_counts()
    )
print(results["Error Type"].value_counts())

# ==========================================================
# MAIN
# ==========================================================

if __name__ == "__main__":

    run_error_evaluation()